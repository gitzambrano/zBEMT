# namespace -> (attribute on Project, dataclass used to validate field/type)
_SET_NAMESPACE_DATACLASS = {
    "config": BEMTConfig,
    "airfoil": AirfoilDef,
    "geom": RotorGeometryDef,
}

_TRUE_STRINGS = {"true", "1", "yes"}
_FALSE_STRINGS = {"false", "0", "no"}


def _unwrap_optional(py_type):
    """`Optional[X]` (== `Union[X, None]`) -> X; any other type, unchanged."""
    if typing.get_origin(py_type) is typing.Union:
        args = [a for a in typing.get_args(py_type) if a is not type(None)]
        if len(args) == 1:
            return args[0]
    return py_type


def _convert_set_value(raw_value: str, py_type, field_name: str):
    py_type = _unwrap_optional(py_type)
    if py_type is bool:
        low = raw_value.strip().lower()
        if low in _TRUE_STRINGS:
            return True
        if low in _FALSE_STRINGS:
            return False
        raise ValueError(
            f"invalid boolean value {raw_value!r} for '{field_name}' "
            f"(use true/false/1/0/yes/no).")
    if py_type is int:
        try:
            return int(raw_value)
        except ValueError:
            raise ValueError(f"invalid integer value {raw_value!r} for '{field_name}'.")
    if py_type is float:
        try:
            return float(raw_value)
        except ValueError:
            raise ValueError(f"invalid numeric value {raw_value!r} for '{field_name}'.")
    if py_type is str:
        return raw_value
    raise ValueError(
        f"field '{field_name}' has type {py_type!r}, not supported by --set "
        f"(lists/dicts are not convertible from a string; use --geom-file/"
        f"--airfoil-sections-file/--airfoil-table for such fields).")


def _apply_set_flags(project, args) -> None:
    """Applies all --set flags, AFTER the dedicated flags (precedence
    documented in --help): in case of conflict, --set wins."""
    if not args.set:
        return

    type_hints_cache: dict = {}
    for item in args.set:
        if "=" not in item:
            raise SystemExit(
                f"--set: invalid format {item!r}, expected NAMESPACE.FIELD=VALUE "
                f"(e.g. --set config.Ne=90).")
        key, raw_value = item.split("=", 1)
        if "." not in key:
            raise SystemExit(
                f"--set: {key!r} needs a namespace (config./airfoil./geom.), "
                f"e.g. --set config.{key}=...")
        ns, field_name = key.split(".", 1)
        dataclass_type = _SET_NAMESPACE_DATACLASS.get(ns)
        if dataclass_type is None:
            raise SystemExit(
                f"--set: invalid namespace {ns!r}. Valid: "
                f"{', '.join(sorted(_SET_NAMESPACE_DATACLASS))}.")

        valid_fields = {f.name for f in dataclasses.fields(dataclass_type)}
        if field_name not in valid_fields:
            raise SystemExit(
                f"--set: field '{ns}.{field_name}' does not exist in "
                f"{dataclass_type.__name__}. Valid fields: "
                f"{', '.join(sorted(valid_fields))}.")

        if dataclass_type not in type_hints_cache:
            type_hints_cache[dataclass_type] = typing.get_type_hints(dataclass_type)
        py_type = type_hints_cache[dataclass_type][field_name]

        try:
            value = _convert_set_value(raw_value, py_type, field_name)
        except ValueError as exc:
            raise SystemExit(f"--set: {exc}")

        if ns == "config":
            project.config[field_name] = value           # dict (asdict of BEMTConfig)
        elif ns == "airfoil":
            setattr(project.airfoil, field_name, value)
        elif ns == "geom":
            setattr(project.geometry, field_name, value)


