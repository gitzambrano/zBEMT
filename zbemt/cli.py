"""Implement the command-line interface for the same workflows as the GUI.

Purpose: parse project, geometry, airfoil, flight-condition, batch, solver, and
export options and delegate all behavior to ``api.py``. Inputs are arguments,
project files, and optional ``--set`` paths. Outputs are validation messages,
results, saved projects, tables, figures, and reports. This module contains no
physics and no independent serialization; axis labels and keys follow
``nomenclature.py``. CLI limitations are the options exposed by the parser and
the physical limitations reported by the selected models.

cli.py
======

Script/CLI equivalent to the GUI. Same ``api.py`` calls that
``zbemt.gui.app`` uses. Zero widgets, zero physics, zero direct I/O.
Everything goes through ``api.py``.

CLI<->GUI<->.bemt parity: every flag of this script sets a
``Project``/``BEMTConfig`` field that is also editable from the GUI, and
every ``.bemt`` file generated by any of the three paths (GUI, CLI,
manual editing) is read back identically by the other two.

Two equivalent ways to use it (every command-line flag has a
corresponding Python field in ``RunOptions``, and vice versa):

    from zbemt.cli import main, RunOptions
    main(["--project", "projects/MyProject", "--rpm", "300"])
    main(options=RunOptions(project="projects/MyProject", rpm=300.0))

Typical command-line usage (``zbemt`` is the installed entry point;
``python -m zbemt.cli`` works identically):

    zbemt --project projects/MyProject
    zbemt --project projects/MyProject --from-bemt-batch hover_sweep
    zbemt --project projects/MyProject --list-batches
    zbemt --new projects/MyProject --radius 0.6 --rpm 1200 \\
        --inflow pitt_peters_steady --dynamic-stall --save-as projects/MyProject
    zbemt --project projects/MyProject \\
        --gen-neuralfoil --airfoil-geometry naca2412 \\
        --reynolds 1e5,5e5,1e6 --mach 0.1,0.3 --alpha-range -10:20:0.5 \\
        --export-table saida/naca2412_neuralfoil.csv
    zbemt --project projects/MyProject --gen-xfoil \\
        --airfoil-geometry naca2412 --reynolds 1e6 --mach 0.3
    zbemt --project projects/MyProject --compare projects/RotorA,projects/RotorB
    zbemt --project projects/MyProject --optimize tip_chord_study --max-evals 60
    zbemt --project projects/MyProject --optimize pareto_study --algorithm nsga2
"""

from __future__ import annotations

import argparse
import dataclasses
import sys
import typing
from pathlib import Path

import numpy as np

# Running the FILE directly (`python zbemt/cli.py`, or the "Run" button of
# an IDE with this file open) executes it as a standalone script, without a
# package. Then every `from . import ...` below raises
# "attempted relative import with no known parent package". Putting the
# repository root on `sys.path` and declaring `__package__` makes the
# relative import resolve, so the "Run" button works the same as
# `python -m zbemt.cli`. Outside that case (normal import, `-m`), this
# block does not run and nothing changes.
if __name__ == "__main__" and __package__ in (None, ""):    # pragma: no cover
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    __package__ = "zbemt"

from . import api
from . import nomenclature
from .models import FlightCondition, BatchDefinition, RotorGeometryDef, AirfoilDef
from . import geometry
from . import airfoils
from .bemt import BEMTConfig


# Running with no arguments (for example, the IDE's "Run" button) uses this example
# project by default.
DEFAULT_PROJECT_PATH = "projects/starter_rotor"

#: RPM for the no-argument run. Must be explicit here: RPM is MANDATORY in
#: every flight condition (`studies._require_rpm` has no default, on
#: purpose, because BEMT non-dimensionalizes everything by Omega*R) and
#: `starter_rotor` ships no saved cases. Without this, the no-argument
#: run used to end in a validation ERROR ("Flight condition without
#: RPM") instead of a clean run. That is a terrible first impression for
#: someone who just hit "Run" to see what the program does.
DEFAULT_RPM = 600.0


# =============================================================================
# Argument parsing
#
# Two ways to set this script's options (requested by the project owner:
# "every command-line flag must also be settable directly in Python"):
#
#   from zbemt.cli import main, RunOptions
#   main(["--project", "projects/X", "--rpm", "300", "--mu-inplane", "0.2"])
#   main(options=RunOptions(project="projects/X", rpm=300.0, mu_inplane=0.2))
#
# `RunOptions` is generated from the argparse.ArgumentParser itself (via
# `_build_run_options_dataclass`), so the two forms can never diverge:
# every flag defined in `_build_parser` automatically becomes a
# `RunOptions` field with the same default, and there is no way to add a
# flag without the corresponding Python field (or vice versa).
# =============================================================================

def _build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Run a new or existing zBEMT project without the GUI, "
                     "through api.py. The CLI has full parity with the GUI "
                     "(docs/parity_registry.md).",
    )
    project_group = p.add_mutually_exclusive_group(required=True)
    project_group.add_argument("--project", metavar="PATH",
                                help="Open an existing project in this folder.")
    project_group.add_argument("--new", metavar="PATH",
                                help="Create a new project (default geometry/airfoil) in this folder.")

    p.add_argument("--name", default=None,
                    help="Project name, used only with --new (default: folder name).")
    p.add_argument("--save-as", metavar="PATH", default=None,
                    help="Save the project in this folder before running, with every "
                         "field set by the flags below already applied. If you omit it, zBEMT "
                         "does not write the flags to disk, and they affect this call only.")

    # --- listing/selecting saved batches and cases (Part 3.3, item 1-2) --
    p.add_argument("--list-batches", action="store_true",
                    help="List saved batches in project.batches and exit.")
    p.add_argument("--list-cases", action="store_true",
                    help="List saved cases in project.saved_cases and exit.")
    p.add_argument("--from-bemt-batch", metavar="NAME", default=None,
                    help="Run the saved batch NAME (project.batches) instead of creating "
                         "an ad hoc condition.")
    p.add_argument("--from-bemt-case", metavar="NAME", default=None,
                    help="Run the saved case NAME (project.saved_cases).")

    # --- External polar table generation (Phase 7, docs/plano_v3.md
    # Part 7.4). Mode independent of running BEMT, exits right after
    # generating (and optionally exporting/applying). One flag per
    # engine; every other option of the group is shared. ---------------
    polar_group = p.add_argument_group("External polar table generation")
    polar_group.add_argument(
        "--gen-neuralfoil", action="store_true",
        help="Generate a polar table via NeuralFoil for --airfoil-geometry and exit "
             "(does not run BEMT). Requires the 'neuralfoil' package (pip install neuralfoil).")
    polar_group.add_argument(
        "--gen-xfoil", action="store_true",
        help="Generate a polar table via XFOIL for --airfoil-geometry and exit "
             "(does not run BEMT). Shares every option of this group with "
             "--gen-neuralfoil. Only the engine differs. The three transition "
             "options below apply to XFOIL only. Stops with an error "
             "when XFOIL support is not available.")
    polar_group.add_argument(
        "--airfoil-geometry", metavar="SPEC", default=None,
        help="Airfoil geometry: a NACA 4-digit or 5-digit code (for example "
             "'naca2412', 'naca23012') "
             f"or a typical rotor-blade preset ({', '.join(sorted(airfoils.AIRFOIL_PRESETS))}).")
    polar_group.add_argument(
        "--reynolds", metavar="R1,R2,...", default=None,
        help="List of Reynolds for the sweep, for example '1e5,5e5,1e6'.")
    polar_group.add_argument(
        "--mach", metavar="M1,M2,...", default=None,
        help="List of Mach for the sweep, for example '0.1,0.3'.")
    polar_group.add_argument(
        "--alpha-range", metavar="MIN:MAX:STEP", default="-10:20:0.5",
        help="Alpha [deg] range for the sweep (default: -10:20:0.5).")
    polar_group.add_argument(
        "--export-table", metavar="PATH", default=None,
        help="Write the generated polar table to PATH (CSV, import format). "
             "If omitted, the table is appended to project.airfoil.table_slices and the project "
             "is saved (equivalent to applying directly from GUI).")
    polar_group.add_argument(
        "--ncrit", type=float, metavar="FLOAT", default=None,
        help="XFOIL only (--gen-xfoil): critical amplification factor N of the "
             "e^N transition criterion. A lower N predicts earlier transition and "
             "a more conservative drag level (default: 9). The option is rejected "
             "together with --gen-neuralfoil.")
    polar_group.add_argument(
        "--xtr-top", type=float, metavar="FLOAT", default=None,
        help="XFOIL only (--gen-xfoil): chord fraction where transition is forced "
             "on the upper surface, in (0, 1]. A value of 1 leaves free transition "
             "(default: 1). The option is rejected together with --gen-neuralfoil.")
    polar_group.add_argument(
        "--xtr-bot", type=float, metavar="FLOAT", default=None,
        help="XFOIL only (--gen-xfoil): chord fraction where transition is forced "
             "on the lower surface, in (0, 1]. A value of 1 leaves free transition "
             "(default: 1). The option is rejected together with --gen-neuralfoil.")

    # --- Design tools: geometry comparison and saved optimization
    # studies. Same early-exit pattern as the group above: they never
    # reach the BEMT batch below. --------------------------------------
    design_group = p.add_argument_group("Design tools")
    design_group.add_argument(
        "--compare", metavar="PROJECTS", default=None,
        help="Compare blade geometries and exit (no batch is run). PROJECTS is a "
             "comma-separated list of other project folders. Each folder becomes one "
             "geometry variant, named after its folder, and the geometry of --project "
             "joins the comparison as the variant named 'base'. Every variant runs the "
             "saved cases of --project. When there are none, pass --rpm to compare at "
             "one default condition. Writes comparison.html and comparison.csv to "
             "the outputs folder of --project.")
    design_group.add_argument(
        "--optimize", nargs="?", const="", default=None, metavar="NAME",
        help="Run one saved optimization study and exit (no batch is run). NAME selects "
             "an entry of project.optimizations by name. Without NAME, the first entry "
             "runs. A study with two objectives, or with algorithm nsga2/de, runs the "
             "Pareto search and writes an HTML report, the front CSV and the "
             "evaluations CSV; otherwise the derivative-free search writes its report "
             "plus a history CSV. Everything lands in the outputs folder.")
    design_group.add_argument(
        "--algorithm", choices=["powell", "nelder-mead", "de", "nsga2"],
        default=None,
        help="Search used by --optimize, overriding the value stored in the study. "
             "nsga2 evolves a Pareto front; de is a global single-result search; "
             "powell and nelder-mead stay derivative-free single-objective.")
    design_group.add_argument(
        "--population", type=int, default=None, metavar="N",
        help="Population of the evolutionary searches (--optimize with nsga2 or de), "
             "overriding the value stored in the study.")
    design_group.add_argument(
        "--generations", type=int, default=None, metavar="N",
        help="Generations of the evolutionary searches, overriding the value stored "
             "in the study.")
    design_group.add_argument(
        "--seed", type=int, default=None, metavar="N",
        help="Seed of the evolutionary searches; the same seed reproduces the same "
             "search.")
    design_group.add_argument(
        "--workers", type=int, default=None, metavar="N",
        help="Evaluation processes requested for the evolutionary searches. Stored "
             "on the study. Each generation is spread over that many "
             "processes, so the wall time falls almost in proportion "
             "until there are more workers than cores.")
    design_group.add_argument(
        "--pareto-csv", metavar="PATH", default=None,
        help="Destination of the Pareto front CSV written by --optimize when the run "
             "is multi-objective. Without it, the file lands beside the report under "
             "the study's own name.")
    design_group.add_argument(
        "--max-evals", type=int, default=None, metavar="N",
        help="Evaluation limit used by --optimize, overriding the value stored in the "
             "study definition. Without this flag, the stored value is kept.")
    design_group.add_argument(
        "--trim", choices=["none", "thrust", "CT"], default="none",
        help="Loading held constant across the --compare variants, so efficiency "
             "is compared at equal loading. 'thrust' or 'CT' reads the target from the "
             "first variant (the reference: the geometry of --project, named 'base') "
             "and, at every condition, trims each other variant to it. Propellers "
             "solve RPM, and rotors solve collective. Trimmed summaries record "
             "the columns trim_target, trim_dof and trim_dof_value. Each trimmed "
             "case bisects one control and costs roughly ten times a direct "
             "solve. With the default none, every variant runs the same controls.")

    # --- Transient maneuvers (SC-12) -------------------------------------
    maneuver_group = p.add_argument_group("Transient maneuver (SC-12)")
    maneuver_group.add_argument(
        "--maneuver", nargs="?", const="", default=None, metavar="NAME",
        help="March one saved trajectory and exit (no batch is run). NAME "
             "selects an entry of project.maneuvers by name; a bare flag "
             "runs the first entry. Writes the time-history CSV and the "
             "transient HTML report into the outputs folder.")
    maneuver_group.add_argument(
        "--maneuver-file", metavar="PATH", default=None,
        help="Run a maneuver defined in a .bemt file OUTSIDE the project "
             "(a saved ManeuverDefinition list).")
    maneuver_group.add_argument(
        "--list-maneuvers", action="store_true",
        help="Print the saved maneuver names of --project.")
    maneuver_group.add_argument(
        "--maneuver-dt", type=float, default=None, metavar="FLOAT",
        help="Override the sample interval dt_s for this run.")
    maneuver_group.add_argument(
        "--maneuver-substeps", type=int, default=None, metavar="INT",
        help="Override substeps_per_step for this run.")
    # NOTE: --rpm already exists below (ad hoc condition speed). --compare
    # reuses it when the project has no saved cases; see _run_compare.

    # --- Stability derivatives (SC-14) -----------------------------------
    derivative_group = p.add_argument_group("Stability derivatives (SC-14)")
    derivative_group.add_argument(
        "--derivatives", nargs="?", const="", default=None, metavar="NAME",
        help="Run a saved stability-derivative study. NAME selects an entry "
             "of project.derivatives; a bare flag runs the first one.")
    derivative_group.add_argument(
        "--list-derivatives", action="store_true",
        help="Print the saved derivative-study names of --project.")
    derivative_group.add_argument(
        "--derivatives-csv", metavar="PATH", default=None,
        help="Write the derivative matrix to this CSV instead of the "
             "default path under the project's outputs folder.")

    # --- ad hoc condition (used only if no --from-bemt-* is given and the
    # project has no batch.conditions) ----------------------------------
    # Phase 8 (docs/CHANGELOG.md): the representations of one component are
    # INTERCHANGEABLE representation pairs of the same physical quantity
    # (Section 6c of bemt.py). One flag per SLOT: the representations of the
    # in-plane component are mutually exclusive with each other, and so are
    # those of the along-shaft one. Parity with the GUI's unit dropdown
    # (RunCaseTab/RunBatchTab), which offers the same choice per row.
    p.add_argument("--rpm", type=float, default=None, help="RPM for ad hoc condition.")
    # NAMED BY SLOT, NOT BY LETTER. The flags and `--project` are parsed in
    # the same pass, so a flag cannot know the project's mode, but the
    # letter does: the in-plane component is mu_x on a rotor and mu_z on a
    # propeller. `--mu-inplane` is the in-plane component in both, and which
    # letter it is shown under is left to the surfaces that know the mode
    # (GUI, results table, report, `.bemt`). See `zbemt/nomenclature.py`.
    inplane_group = p.add_mutually_exclusive_group()
    inplane_group.add_argument("--mu-inplane", dest="mu_inplane", type=float, default=None,
                               help="IN-PLANE advance ratio (default 0.0, hover): "
                                    "V_inplane/(Omega*R). The component in the plane of "
                                    "the disk: a rotor's forward-flight advance, or a "
                                    "propeller's CROSS-flow (zero in straight cruise). "
                                    "Alternative to --j-inplane/--v-inplane.")
    inplane_group.add_argument("--j-inplane", dest="J_inplane", type=float, default=None,
                               help="IN-PLANE advance ratio in propeller form: "
                                    "V_inplane/(n*D) = pi*mu_inplane. NOT a propeller's "
                                    "own advance ratio. That one is along the shaft, "
                                    "--j-axial. Alternative to --mu-inplane.")
    inplane_group.add_argument("--v-inplane", dest="V_inplane", type=float, default=None,
                               help="IN-PLANE velocity [m/s]. Requires --rpm (the ratio "
                                    "is V/(Omega*R), and Omega comes from the RPM). "
                                    "Alternative to --mu-inplane.")
    inplane_group.add_argument("--alpha-disk-deg", dest="alpha_disk_deg", type=float, default=None,
                             help="Angle [deg] between the free stream and the SHAFT "
                                  "(0 = straight axial cruise, the propeller convention). "
                                  "The IN-PLANE component is derived from it and from the "
                                  "along-shaft one (--v-axial/--j-axial/--mu-axial), which "
                                  "is therefore required. "
                                  "Complement of --alpha-rotor-deg; the two are mutually "
                                  "exclusive because neither would set the velocity scale.")
    axial_group = p.add_mutually_exclusive_group()
    axial_group.add_argument("--v-axial", dest="V_axial", type=float, default=None,
                             help="ALONG-SHAFT velocity [m/s] (default 0.0): a rotor's "
                                  "climb (+) or descent (-), a propeller's AIRSPEED. "
                                  "Alternative to "
                                  "--j-axial/--mu-axial/--alpha-rotor-deg.")
    axial_group.add_argument("--j-axial", dest="J_axial", type=float, default=None,
                             help="ALONG-SHAFT advance ratio in propeller form: "
                                  "V_axial/(n*D). On a propeller this is THE J of the "
                                  "propeller charts, the one propulsive efficiency uses. "
                                  "Requires --rpm. Alternative to --v-axial.")
    axial_group.add_argument("--mu-axial", dest="mu_axial", type=float, default=None,
                             help="ALONG-SHAFT advance ratio in rotor form: "
                                  "V_axial/(Omega*R) = J_axial/pi. The same number as the "
                                  "free-stream inflow ratio lambda. Requires --rpm. "
                                  "Alternative to --v-axial.")
    axial_group.add_argument("--alpha-rotor-deg",
                              dest="alpha_rotor_deg", type=float, default=None,
                              help="Disk angle of attack [deg]. The ALONG-SHAFT "
                                   "component is derived from the in-plane one, --rpm "
                                   "(required with this flag) and the project's rotor "
                                   "radius. Measured from the disk PLANE and POSITIVE "
                                   "when the stream arrives from BELOW the disk, as an "
                                   "angle of attack is for a wing: a positive angle "
                                   "therefore gives a NEGATIVE along-shaft component, "
                                   "which opposes the induced velocity and raises the "
                                   "thrust. -90 deg is purely axial with the stream from "
                                   "above (climb). For the propeller convention, measured "
                                   "from the shaft and zero in straight cruise, use "
                                   "--alpha-disk-deg. Alternative to --v-axial. "
                                   "Rotor mode only; a propeller reads --alpha-disk-deg. "
                                   "(--disk-alpha-deg is kept as an alias of this flag.)")
    # The THIRD component (SC-15). The disk plane holds two directions, and
    # the in-plane group above names only one of them. This group names the
    # other, so the free stream can arrive from the side. Named by slot for
    # the same reason as the in-plane one: the letter y is lateral in both
    # modes, but the flag stays parallel to its two siblings.
    lateral_group = p.add_mutually_exclusive_group()
    lateral_group.add_argument("--v-lateral", dest="V_lateral", type=float, default=None,
                               help="LATERAL velocity [m/s] (default 0.0): the "
                                    "component sideways and in the plane of the "
                                    "disk. Sideward flight, or flight with "
                                    "sideslip. Alternative to "
                                    "--mu-lateral/--j-lateral/--sideslip-deg.")
    lateral_group.add_argument("--mu-lateral", dest="mu_lateral", type=float, default=None,
                               help="LATERAL advance ratio: V_lateral/(Omega*R). "
                                    "Requires --rpm. Alternative to --v-lateral.")
    lateral_group.add_argument("--j-lateral", dest="J_lateral", type=float, default=None,
                               help="LATERAL advance ratio in propeller form: "
                                    "V_lateral/(n*D) = pi*mu_lateral. Requires "
                                    "--rpm. Alternative to --v-lateral.")
    lateral_group.add_argument("--sideslip-deg", dest="sideslip_deg", type=float, default=None,
                               help="Sideslip angle [deg] of the in-plane free "
                                    "stream, atan2(V_lateral, V_inplane). It "
                                    "SPLITS the in-plane component into a lateral "
                                    "one and never sets the scale of a velocity, "
                                    "so it stays inside -89 to 89. For pure "
                                    "sideward flight use --v-lateral. Alternative "
                                    "to --v-lateral.")
    p.add_argument("--collective", type=float, default=8.0, help="Collective pitch [deg] for ad hoc.")
    p.add_argument("--cyclic", dest="cyclic", nargs=2, type=float, default=None,
                   metavar=("C", "S"),
                   help="Cyclic pitch for the ad hoc condition: the cosine and "
                        "sine 1/rev harmonics (theta_1c theta_1s), both in "
                        "degrees. It reaches the engine through the blade-motion "
                        "path, so it takes effect on a rigid blade only as an "
                        "azimuthal pitch; with flap freedom (SC-11) it is one "
                        "of the cyclic controls.")

    # --- Geometry (RotorGeometryDef) -- Part 3.3, geometry group ---------
    p.add_argument("--geom-preset", choices=["rectangular", "tapered", "elliptic", "custom"],
                    default=None, help="Generate project.geometry from a parametric preset.")
    p.add_argument("--geom-file", metavar="PATH", default=None,
                    help="Load entire project.geometry from a .bemt (RotorGeometryDef).")
    p.add_argument("--geom-radius", type=float, default=None,
                    help="Set the rotor radius, in metres (RotorGeometryDef.radius_m).")
    p.add_argument("--geom-root-cutout", type=float, default=None,
                    help="Set the root cutout, as a fraction of the radius "
                         "(RotorGeometryDef.root_cutout_norm).")
    p.add_argument("--geom-n-blades", type=int, default=None,
                    help="Set the number of blades (RotorGeometryDef.n_blades).")
    p.add_argument("--geom-chord", type=float, default=None,
                    help="constant chord_norm (rectangular preset).")
    p.add_argument("--geom-taper-ratio", type=float, default=None,
                    help="tip_chord_norm/root_chord_norm (tapered preset; requires --geom-chord "
                         "as root_chord_norm).")
    p.add_argument("--geom-max-chord", type=float, default=None,
                    help="max_chord_norm (elliptic preset).")
    p.add_argument("--geom-twist-root", type=float, default=None,
                    help="Set the generated twist at the root, in degrees "
                         "(linear twist preset).")
    p.add_argument("--geom-twist-tip", type=float, default=None,
                    help="Set the generated twist at the tip, in degrees "
                         "(linear twist preset).")
    p.add_argument("--geom-custom-points", metavar="r:c:t,r:c:t,...", default=None,
                    help="Point-by-point table (custom preset): r/R:chord_norm:twist_deg, "
                         "separated by comma.")

    # --- Blade dynamics (RotorGeometryDef.dynamics) -- SC-11 -------------
    p.add_argument("--flap-model", choices=["rigid", "offset", "spring", "offset_spring"],
                   default=None,
                   help="Choose the blade's flap freedom "
                        "(RotorGeometryDef.dynamics.flap_model): a rigid disk, a "
                        "hinge offset, a root spring, or both together.")
    p.add_argument("--hinge-offset", type=float, default=None,
                   help="Flap hinge offset e, as a fraction of the radius "
                        "(dynamics.hinge_offset_norm), 0 to 0.3.")
    p.add_argument("--lock-number", type=float, default=None,
                   help="Lock number gamma of the blade "
                        "(dynamics.lock_number); sets the aerodynamic-to-"
                        "inertial response ratio when the inertia source is "
                        "the Lock number.")

    # --- Airfoil (AirfoilDef) -- Part 3.3 -------------------------------
    p.add_argument("--airfoil-source", choices=["analytical", "table"], default=None,
                    help="Choose where the polar comes from (AirfoilDef.source).")
    p.add_argument("--airfoil-table", metavar="CSV", default=None,
                    help="Import a polar table (CSV) to AirfoilDef.table_slices "
                         "and set source='table' (same importer as airfoils.import_polar_csv).")
    p.add_argument("--dynamic-stall", dest="dynamic_stall", action="store_true", default=None,
                    help="Turn dynamic stall on (AirfoilDef.use_dynamic_stall=True).")
    p.add_argument("--no-dynamic-stall", dest="dynamic_stall", action="store_false",
                    help="Turn dynamic stall off (AirfoilDef.use_dynamic_stall=False).")
    # There is no flag for BEMTConfig.dynamic_stall_model: today only one
    # model is supported ("oye"), so the field has no real choice to
    # expose in the CLI. What turns dynamic stall on/off is the boolean
    # --dynamic-stall/--no-dynamic-stall above. The field still exists
