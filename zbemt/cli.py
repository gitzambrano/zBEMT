def _apply_geometry_flags(project, args) -> None:
    g = project.geometry

    # `--geom-file` used to sit in an `elif` AFTER all the presets, so
    # `--geom-preset X --geom-file Y` used the preset and silently
    # discarded the file. There is no obvious answer for which should win, so
    # the right move is to reject the combination rather than pick one on our own.
    if args.geom_preset and args.geom_file:
        raise SystemExit(
            "cli.py: --geom-preset and --geom-file are mutually exclusive "
            "(both define the entire geometry). Choose one.")

    if args.geom_preset == "rectangular":
        project.geometry = geometry.generate_rectangular(
            root_cutout_norm=args.geom_root_cutout if args.geom_root_cutout is not None else g.root_cutout_norm,
            radius_m=args.geom_radius if args.geom_radius is not None else g.radius_m,
            chord_norm=args.geom_chord if args.geom_chord is not None else 0.08,
            twist_root_deg=args.geom_twist_root if args.geom_twist_root is not None else 12.0,
            twist_tip_deg=args.geom_twist_tip if args.geom_twist_tip is not None else 4.0,
            n_blades=args.geom_n_blades if args.geom_n_blades is not None else g.n_blades,
            airfoil_name=g.airfoil_name,
        )
    elif args.geom_preset == "tapered":
        root_chord = args.geom_chord if args.geom_chord is not None else 0.10
        tip_chord = root_chord * args.geom_taper_ratio if args.geom_taper_ratio is not None else 0.04
        project.geometry = geometry.generate_tapered(
            root_cutout_norm=args.geom_root_cutout if args.geom_root_cutout is not None else g.root_cutout_norm,
            radius_m=args.geom_radius if args.geom_radius is not None else g.radius_m,
            root_chord_norm=root_chord, tip_chord_norm=tip_chord,
            twist_root_deg=args.geom_twist_root if args.geom_twist_root is not None else 14.0,
            twist_tip_deg=args.geom_twist_tip if args.geom_twist_tip is not None else 2.0,
            n_blades=args.geom_n_blades if args.geom_n_blades is not None else g.n_blades,
            airfoil_name=g.airfoil_name,
        )
    elif args.geom_preset == "elliptic":
        project.geometry = geometry.generate_elliptic(
            root_cutout_norm=args.geom_root_cutout if args.geom_root_cutout is not None else g.root_cutout_norm,
            radius_m=args.geom_radius if args.geom_radius is not None else g.radius_m,
            max_chord_norm=args.geom_max_chord if args.geom_max_chord is not None else 0.10,
            twist_root_deg=args.geom_twist_root if args.geom_twist_root is not None else 14.0,
            twist_tip_deg=args.geom_twist_tip if args.geom_twist_tip is not None else 2.0,
            n_blades=args.geom_n_blades if args.geom_n_blades is not None else g.n_blades,
            airfoil_name=g.airfoil_name,
        )
    elif args.geom_preset == "custom":
        if not args.geom_custom_points:
            raise SystemExit("--geom-preset custom requires --geom-custom-points r:c:t,...")
        r_norm, chord_norm, twist_deg = [], [], []
        for point in args.geom_custom_points.split(","):
            r, c, t = point.split(":")
            r_norm.append(float(r)); chord_norm.append(float(c)); twist_deg.append(float(t))
        project.geometry = geometry.generate_custom(
            r_norm, chord_norm, twist_deg,
            radius_m=args.geom_radius if args.geom_radius is not None else g.radius_m,
            n_blades=args.geom_n_blades if args.geom_n_blades is not None else g.n_blades,
            airfoil_name=g.airfoil_name,
        )
    elif args.geom_file:
        from .models import load_bemt
        project.geometry = load_bemt(RotorGeometryDef, args.geom_file)
    else:
        # no preset/file: only overrides loose scalar fields, if given
        if args.geom_radius is not None:
            g.radius_m = args.geom_radius
        if args.geom_root_cutout is not None:
            g.root_cutout_norm = args.geom_root_cutout
        if args.geom_n_blades is not None:
            g.n_blades = args.geom_n_blades

    # --- blade dynamics (SC-11): the three fields a user changes most ----
    d = project.geometry.dynamics
    if args.flap_model is not None:
        d.flap_model = args.flap_model
    if args.hinge_offset is not None:
        d.hinge_offset_norm = args.hinge_offset
    if args.lock_number is not None:
        d.lock_number = args.lock_number


