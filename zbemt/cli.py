def main(argv=None, options=None) -> int:
    # If called with no arguments (argv=None and sys.argv empty), inject a default.
    # This allows running as "python zbemt/cli.py" and getting useful behavior
    # without breaking usage with explicit argv or RunOptions.
    if argv is None and options is None and len(sys.argv) == 1:
        argv = ["--project", DEFAULT_PROJECT_PATH,
                "--rpm", str(DEFAULT_RPM), "--validate-only"]

    args = options if options is not None else RunOptions.from_argv(argv)

    if args.new:
        project = api.new_project(args.new, name=args.name)
        project_path = args.new
    else:
        try:
            project = api.open_project(args.project)
        except (ValueError, OSError) as exc:
            # A project that cannot be read is the user's file being
            # wrong, not the program failing. A traceback buries the one
            # line that says which condition is at fault.
            print(f"cli.py: error: cannot open {args.project!r}: {exc}",
                  file=sys.stderr)
            return 2
        project_path = args.project

    if args.list_batches:
        # A sweep batch stores `sweep_params`, not a list of conditions.
        # Printing `len(conditions)` said "0 condition(s)" for all of
        # them, which sounded like an empty batch. What matters here is
        # how many cases the sweep WILL generate.
        for b in project.batches:
            if b.conditions:
                count_text = f"{len(b.conditions)} explicit condition(s)"
            else:
                params = b.sweep_params or {}
                if b.sweep_kind == "factorial":
                    # Factorial: the product of the axes, not the number of axes.
                    axes = [axis.get("values", []) for axis in params.get("axes", [])]
                else:
                    axes = [v for v in params.values() if isinstance(v, (list, tuple))]
                n = 1
                for axis in axes:
                    n *= max(len(axis), 1)
                count_text = (f"{n} sweep case(s)" if axes
                              else "no conditions defined")
            print(f"{b.name}\t{count_text}\tsweep_kind={b.sweep_kind}")
        return 0
    if args.list_cases:
        for c in project.saved_cases:
            print(f"{c.name}\tmu={c.mu_x}\tcollective_deg={c.collective_deg}\tVv={c.Vz}\trpm={c.rpm}")
        return 0
    if args.list_derivatives:
        studies = getattr(project, "derivatives", [])
        if not studies:
            print("This project stores no derivative studies "
                  "(inputs/derivatives.bemt absent or empty).")
        for d in studies:
            variables = ", ".join([*d.states, *d.controls]) or "(none)"
            print(f"{d.name}\ttrim={d.trim}\tvariables: {variables}")
        return 0
    if args.list_maneuvers:
        maneuvers = getattr(project, "maneuvers", [])
        if not maneuvers:
            print("This project stores no maneuvers "
                  "(inputs/maneuvers.bemt absent or empty).")
        for m in maneuvers:
            times = ", ".join(f"{p.t_s:g}s" for p in m.points[:4])
            more = " ..." if len(m.points) > 4 else ""
            print(f"{m.name}\t{len(m.points)} point(s)\tt: {times}{more}\t"
                  f"dt={m.dt_s:g}s")
        return 0

    # The design-tool modes are alternative jobs, not modifiers: each one
    # runs its own workflow and writes its own artifacts, so two of them
    # in one call has no defined meaning. argparse cannot express this
    # conflict (the polar flags and the design flags live in different
    # argument groups), so the check is explicit. It sits before any flag
    # application because it is a pure command-line conflict.
    selected_modes = [flag for flag, given in (
        ("--compare", bool(args.compare)),
        ("--optimize", args.optimize is not None),
        ("--gen-neuralfoil", bool(args.gen_neuralfoil)),
        ("--gen-xfoil", bool(args.gen_xfoil)),
        ("--maneuver", args.maneuver is not None),
        ("--derivatives", args.derivatives is not None),
    ) if given]
    if len(selected_modes) > 1:
        print("cli.py: error: " + ", ".join(selected_modes)
              + " are mutually exclusive. Give at most one of "
              "--compare, --optimize, --gen-neuralfoil, --gen-xfoil, "
              "--maneuver or --derivatives.",
              file=sys.stderr)
        return 2

    if args.gen_neuralfoil:
        return _run_gen_polar(project, project_path, args, "neuralfoil")
    if args.gen_xfoil:
        return _run_gen_polar(project, project_path, args, "xfoil")
    if args.compare:
        return _run_compare(project, args)
    if args.optimize is not None:
        return _run_optimize(project, args)
    if args.maneuver is not None:
        return _run_maneuver(project, args)
    if args.derivatives is not None:
        return _run_derivatives(project, args)

    _apply_geometry_flags(project, args)
    _apply_airfoil_flags(project, args)
    _apply_config_flags(project, args)
    _apply_set_flags(project, args)   # AFTER the dedicated ones: --set wins on conflict

    if args.save_as:
        project.path = args.save_as
        api.save_project(project)
        project_path = args.save_as

    # --- resolve what to run: saved batch > saved case > existing
    # batch.conditions > ad hoc condition (parity Part 3.3, item 1-2) -----
    # The two angles are in different exclusive GROUPS (the axis one is
    # the in-plane component, and the disk one is the axial), so `argparse`
    # cannot express "one from each group, except this combination".
    # Without the explicit check, `--alpha-disk-deg 6 --alpha-rotor-deg 84`
    # used to pass and resolve Vz from a still-zero mu_x: Vz=0, a silent
    # hover condition instead of the requested cruise.
    if args.alpha_disk_deg is not None and args.alpha_rotor_deg is not None:
        print("cli.py: error: --alpha-disk-deg and --alpha-rotor-deg are the "
              "same angle written two ways (alpha_disk = 90 - alpha_rotor): with "
              "both, neither velocity component sets the scale. Give one angle "
              "plus a dimensional or non-dimensional component "
              "(--vz/--jz/--muz for the axial one, --mux/--jx for the in-plane).",
              file=sys.stderr)
        return 2

    if args.from_bemt_batch:
        batch = api.get_batch(project, args.from_bemt_batch)
    elif args.from_bemt_case:
        case = api.get_saved_case(project, args.from_bemt_case)
        batch = BatchDefinition(name=f"cli_case_{case.name}", conditions=[case])
    else:
        radius_m = project.geometry.radius_m

        def _axial(mu_known: float):
            """Axial component [m/s]. Only the disk-angle branch depends
            on the already-resolved in-plane component."""
            if args.alpha_rotor_deg is not None:
                if args.rpm is None:
                    return None, ("cli.py: error: --alpha-rotor-deg requires --rpm "
                                  "(the axial component is derived from the in-plane "
                                  "one, the rpm and the rotor radius).")
                return api.vv_from_alpha_deg(args.alpha_rotor_deg, mu_known,
                                              args.rpm, radius_m), None
            if args.J_axial is not None or args.mu_axial is not None:
                if args.rpm is None:
                    return None, ("cli.py: error: --j-axial/--mu-axial require --rpm "
                                  "(the axial speed is mu*Omega*R, and Omega comes "
                                  "from the RPM).")
                mu = (api.J_to_mu(args.J_axial) if args.J_axial is not None
                      else args.mu_axial)
                return api.mu_to_V(mu, args.rpm, radius_m), None
            if args.V_axial is not None:
                return args.V_axial, None
            return 0.0, None

        # ORDER: normally the in-plane component is the known one and the
        # axial one can be derived from it (--alpha-rotor-deg). With
        # --alpha-disk-deg the dependency inverts, because the in-plane comes out
        # of the axial, so the axial comes first. Same inversion as
        # `bemt.resolve_advance_velocity`.
        if args.alpha_disk_deg is not None:
            if args.rpm is None:
                print("cli.py: error: --alpha-disk-deg requires --rpm "
                      "(the in-plane component is tan(alpha_disk)*Vz, and mu_x needs Omega*R).",
                      file=sys.stderr)
                return 2
            Vz, error_message = _axial(0.0)
            if error_message:
                print(error_message, file=sys.stderr)
                return 2
            # |Vz|: same reason as `bemt.resolve_advance_velocity`.
            mu_x = api.V_to_mu(
                float(np.tan(np.deg2rad(args.alpha_disk_deg))) * abs(Vz),
                args.rpm, radius_m)
        else:
            if args.mu_inplane is not None:
                mu_x = args.mu_inplane
            elif args.J_inplane is not None:
                mu_x = api.J_to_mu(args.J_inplane)
            elif args.V_inplane is not None:
                if args.rpm is None:
                    print("cli.py: error: --v-inplane requires --rpm (the ratio is "
                          "V/(Omega*R), and Omega comes from the RPM).", file=sys.stderr)
                    return 2
                mu_x = api.V_to_mu(args.V_inplane, args.rpm, radius_m)
            else:
                mu_x = 0.0   # default: hover
            Vz, error_message = _axial(mu_x)
            if error_message:
                print(error_message, file=sys.stderr)
                return 2

        # The lateral component (SC-15). The angle spelling travels as the
        # angle, exactly as a saved case carries it; the three velocity
        # spellings become `Vy`. Only one of the two ever leaves here
        # non-zero, which is the rule `validation` enforces.
        Vy, sideslip_deg = 0.0, 0.0
        if args.sideslip_deg is not None:
            sideslip_deg = float(args.sideslip_deg)
        elif args.V_lateral is not None:
            Vy = float(args.V_lateral)
        elif args.mu_lateral is not None or args.J_lateral is not None:
            if args.rpm is None:
                print("cli.py: error: --mu-lateral/--j-lateral require --rpm "
                      "(the ratio is V/(Omega*R), and Omega comes from the RPM).",
                      file=sys.stderr)
                return 2
            mu_y = (float(args.mu_lateral) if args.mu_lateral is not None
                    else api.J_to_mu(float(args.J_lateral)))
            Vy = api.mu_to_V(mu_y, args.rpm, radius_m)

        condition = FlightCondition(
            name="cli", rpm=args.rpm, mu_x=mu_x, Vz=Vz,
            Vy=Vy, sideslip_deg=sideslip_deg,
            collective_deg=args.collective,
            cyclic_c_deg=(args.cyclic[0] if args.cyclic else 0.0),
            cyclic_s_deg=(args.cyclic[1] if args.cyclic else 0.0),
        )
        batch = BatchDefinition(name="cli_adhoc", conditions=[condition])

    # Validation BEFORE running: without this, a configuration the solver
    # rejects (an unimplemented inflow model, an unknown airfoil source)
    # only failed deep inside, with a raw traceback, possibly
    # after hours of unsupervised batch. `api.validate_project` already
    # existed exactly for this and the CLI never called it.
    issues = api.validate_project(project, conditions=batch.conditions)
    errors = [i for i in issues if i.level == "error"]
    if issues:
        stream = sys.stderr if errors else sys.stdout
        print("Project validation:", file=stream)
        for issue in issues:
            print(f"  {issue}", file=stream)
    if errors and not args.ignore_validation_errors:
        print(f"\ncli.py: {len(errors)} validation error(s). Nothing was run.\n"
              f"Use --ignore-validation-errors to run anyway.", file=sys.stderr)
        return 2

    if args.validate_only:
        print("\n--validate-only: project verified, nothing was run.")
        return 0

    if args.trim_mode is not None:
        if args.trim_target_thrust is None and args.trim_target_ct is None:
            print("cli.py: error: --trim-mode requires --trim-target-thrust or --trim-target-ct.",
                  file=sys.stderr)
            return 2
        target_kind = "thrust" if args.trim_target_thrust is not None else "CT"
        target_value = args.trim_target_thrust if args.trim_target_thrust is not None else args.trim_target_ct
        try:
            results = api.run_batch(project, batch, trim_mode=args.trim_mode,
                                    target_kind=target_kind, target_value=target_value)
        except ValueError as exc:
            print(f"cli.py: error: {exc}", file=sys.stderr)
            return 2
    else:
        results = api.run_batch(project, batch)

    # `batch` here may be a NAMED batch (--from-bemt-batch) or the ad hoc
    # one built above, either of which may carry its own outdir/plots.
    outdir = args.outdir or batch.outdir or str(Path(project_path) / "outputs")
    # `--plots` with no values (nargs="*") becomes [], which is not None
    # and therefore SUPPRESSED the project's plots instead of falling back
    # to the default. An explicit empty list now means "no plots", and the
    # flag's absence still means "use what the project asked for".
    if args.plots is None:
        plots = batch.plots or None
    else:
        plots = args.plots or None

    written = api.export_results(results, outdir=outdir, plots=plots,
                                  save_csv=not args.no_csv, project=project,
                                  layout=args.export_layout)

    # The report uses the plots that apply to the selection (default of
    # `api.generate_report`), regardless of `--plots`: `--plots` controls
    # what ends up on disk as standalone PNGs, `--report` controls what
    # gets embedded in the HTML. Passing an empty `--plots` to save files
    # should not empty out the report.
    if args.report is not None:
        report_path = args.report or str(Path(outdir) / "report.html")
        written.append(str(api.generate_report(
            results, report_path, project=project,
            title=f"zBEMT Report: {project.name}",
            notes=args.report_notes)))

    # Both coefficient families are always in `summary` (see
    # `bemt.aggregate_results`). What changes is which one the user wants
    # to read. Printing FM for a propeller is worse than useless: FM is the
    # figure of merit for HOVER, and an aircraft propeller never hovers.
    # The number comes out low and looks like a bad design, when the
    # metric simply does not apply. The one that fills this role on the
    # propeller side is `eta_prop`.
    is_propeller = bool(project.config.get("is_propeller"))
    if is_propeller:
        coeff_keys = ("J_z", "CT_prop", "CQ_prop", "CP_prop", "eta_prop")
    else:
        coeff_keys = ("CT", "CQ", "CP", "FM")

    for res in results:
        summary = res.summary
        keys = [k for k in coeff_keys if k in summary]
        # The key is the ENGINE's. What gets printed is the letter this mode
        # shows: a propeller's along-shaft advance ratio is J_x on screen,
        # in the report and in its `.bemt` file, so printing the internal
        # `J_z` here would make the CLI the one surface that disagrees.
        parts = ", ".join(
            f"{nomenclature.display_key(k, is_propeller)}={summary[k]:.5g}"
            for k in keys)
        print(f"[{res.condition_name}] {parts}")

    if written:
        print("Files generated:")
        for w in written:
            print(f"  {w}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
