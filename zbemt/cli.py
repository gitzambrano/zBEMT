def _preprocess_argv(argv=None) -> list[str]:
    """Normalizes `argv` before parsing: `--alpha-range VAL` becomes
    `--alpha-range=VAL` so argparse is not confused when VAL starts
    with `-` (for example negative ranges, "-10:20:0.5")."""
    if argv is None:
        argv = sys.argv[1:]
    else:
        argv = list(argv)

    new_argv = []
    i = 0
    while i < len(argv):
        arg = argv[i]
        if arg == "--alpha-range" and i + 1 < len(argv):
            new_argv.append(f"--alpha-range={argv[i+1]}")
            i += 2
        else:
            new_argv.append(arg)
            i += 1
    return new_argv


def _parse_args(argv=None) -> argparse.Namespace:
    return _build_parser().parse_args(_preprocess_argv(argv))


def _build_run_options_dataclass(parser: argparse.ArgumentParser):
    """Derives a dataclass with one field per parser flag (same `dest`,
    same default), so that `RunOptions` can never diverge from the
    argparse's real flags."""
    fields = []
    seen = set()
    for action in parser._actions:
        if isinstance(action, argparse._HelpAction):
            continue
        dest = action.dest
        if dest == argparse.SUPPRESS or dest in seen:
            continue
        seen.add(dest)
        default = action.default
        # dataclasses rejects a mutable default (list/dict/set) directly,
        # for example `--set` (action="append", default=[]). default_factory
        # captures the value by copy so instances don't share the same list.
        if isinstance(default, (list, dict, set)):
            fields.append((dest, typing.Any,
                            dataclasses.field(default_factory=lambda d=default: type(d)(d))))
        else:
            fields.append((dest, typing.Any, dataclasses.field(default=default)))
    return dataclasses.make_dataclass("RunOptions", fields)


RunOptions = _build_run_options_dataclass(_build_parser())


def _run_options_from_argv(cls, argv=None):
    ns = _parse_args(argv)
    return cls(**{f.name: getattr(ns, f.name) for f in dataclasses.fields(cls)})


RunOptions.from_argv = classmethod(_run_options_from_argv)


