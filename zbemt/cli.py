"""Implement the command-line interface for the same workflows as the GUI.

Purpose: parse project, geometry, airfoil, flight-condition, batch, solver, and
export options and delegate all behavior to ``api.py``. Inputs are arguments,
project files, and optional ``--set`` paths. Outputs are validation messages,
results, saved projects, tables, figures, and reports. This module contains no
physics and no independent serialization; axis labels and keys follow
``nomenclature.py``. CLI limitations are the options exposed by the parser and
the physical limitations reported by the selected models.

cli.py
======

Script/CLI equivalent to the GUI. Same ``api.py`` calls that
``zbemt.gui.app`` uses; zero widgets, zero physics, zero direct I/O --
everything goes through ``api.py``.

CLI<->GUI<->.bemt parity: every flag of this script sets a
``Project``/``BEMTConfig`` field that is also editable from the GUI, and
every ``.bemt`` file generated by any of the three paths (GUI, CLI,
manual editing) is read back identically by the other two.

Two equivalent ways to use it (every command-line flag has a
corresponding Python field in ``RunOptions``, and vice versa):

    from zbemt.cli import main, RunOptions
    main(["--project", "projects/MyProject", "--rpm", "300"])
    main(options=RunOptions(project="projects/MyProject", rpm=300.0))

Typical command-line usage (``zbemt`` is the installed entry point;
``python -m zbemt.cli`` works identically):

    zbemt --project projects/MyProject
    zbemt --project projects/MyProject --from-bemt-batch hover_sweep
    zbemt --project projects/MyProject --list-batches
    zbemt --new projects/MyProject --radius 0.6 --rpm 1200 \\
        --inflow pitt_peters_steady --dynamic-stall --save-as projects/MyProject
    zbemt --project projects/MyProject \\
        --gen-neuralfoil --airfoil-geometry naca2412 \\
        --reynolds 1e5,5e5,1e6 --mach 0.1,0.3 --alpha-range -10:20:0.5 \\
        --export-table saida/naca2412_neuralfoil.csv
"""

